import assert from 'node:assert/strict';
import { chromium, expect } from '@playwright/test';
import { mkdtemp, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { createService } from '../server/service.mjs';
import { startHarness } from './harness.mjs';
import { buildReviewDraft } from './fixtures/review-draft.mjs';

const directory = await mkdtemp(path.join(tmpdir(), 'elis-polish-'));
const service = createService({ dataDir: directory });
const call = (name, args = {}) => service.execute(name, { ...args, request_id: randomUUID() });
const harness = await startHarness(service);
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const output = 'docs/previews/polish';
await mkdir(output, { recursive: true });
try {
  const batch = await call('add_words', { text: 'compelling retain diminish impose conventional' });
  const added = await call('confirm_import', { import_id: batch.import_id, items: batch.items });
  const selection = (await call('select_target_words', { mode: 'manual', manual_ids: added.words.map(word => word.id) })).selection;
  const generation = (await call('prepare_article', { selection_id: selection.id, config: { topic: 'AI 与大学学习', length: 'short' } })).generation;
  const article = (await call('save_article', { generation_id: generation.id, draft: await buildReviewDraft(service) })).article;
  const more = await call('add_words', { text: Array.from({ length: 27 }, (_, index) => `sample${String.fromCharCode(97 + Math.floor(index / 26))}${String.fromCharCode(97 + index % 26)}`).join(' ') });
  await call('confirm_import', { import_id: more.import_id, items: more.items });
  const page = await browser.newPage({ viewport: { width: 1280, height: 854 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(harness.url);
  const ui = page.frameLocator('#app');
  await ui.getByText('词库已连接', { exact: true }).waitFor();
  await expect(ui.getByRole('button', { name: '词库', exact: true })).toHaveAttribute('aria-current', 'page');

  const settingsButton = ui.getByRole('button', { name: '学习设置', exact: true });
  await settingsButton.click();
  let dialog = ui.getByRole('dialog', { name: '按你的习惯学习' });
  await expect(ui.locator('.app-shell')).toHaveAttribute('inert', '');
  await dialog.getByRole('button', { name: '深色', exact: true }).click();
  await expect(ui.locator('html')).toHaveAttribute('data-theme', 'dark');
  await dialog.getByRole('button', { name: '关闭设置', exact: true }).press('Escape');
  await expect(dialog).toHaveCount(0);
  await expect(ui.locator('html')).toHaveAttribute('data-theme', 'light');
  assert.equal(await settingsButton.evaluate(node => node === document.activeElement), true);

  await settingsButton.click();
  await dialog.getByRole('button', { name: '深色', exact: true }).click();
  await dialog.getByRole('button', { name: '24', exact: true }).click();
  await dialog.getByRole('button', { name: '宽松', exact: true }).click();
  await dialog.getByRole('checkbox').uncheck();
  await page.screenshot({ animations: 'disabled', path: `${output}/settings-dark.png` });
  harness.setOffline(true);
  await dialog.getByRole('button', { name: '保存设置', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('词库服务不可达');
  assert.equal((await call('get_preferences')).preferences.appearance, undefined);
  await expect(dialog.getByRole('button', { name: '24', exact: true })).toHaveAttribute('aria-pressed', 'true');
  harness.setOffline(false);
  await dialog.getByRole('button', { name: '保存设置', exact: true }).click();
  await expect(dialog).toHaveCount(0);
  await page.reload(); await ui.getByText('词库已连接', { exact: true }).waitFor();
  await expect(ui.locator('html')).toHaveAttribute('data-theme', 'dark');
  await page.evaluate(() => window.setTheme('light'));
  await expect(ui.locator('html')).toHaveAttribute('data-theme', 'dark');
  await settingsButton.click();
  await dialog.getByRole('button', { name: '恢复默认', exact: true }).click();
  await dialog.getByRole('button', { name: '关闭设置', exact: true }).focus();
  await dialog.getByRole('button', { name: '关闭设置', exact: true }).press('Shift+Tab');
  assert.equal(await dialog.getByRole('button', { name: '保存设置', exact: true }).evaluate(node => node === document.activeElement), true);
  await dialog.getByRole('button', { name: '保存设置', exact: true }).click();

  await ui.getByRole('checkbox', { name: '勾选本页单词', exact: true }).check();
  await expect(ui.locator('.word-row input[type=checkbox]:checked')).toHaveCount(12);
  await ui.getByRole('button', { name: '下一页', exact: true }).click();
  await ui.locator('.word-row').first().getByRole('checkbox').check();
  await expect(ui.getByRole('checkbox', { name: '勾选本页单词', exact: true })).toHaveJSProperty('indeterminate', true);
  await ui.getByRole('combobox', { name: '每页词数', exact: true }).selectOption('24');
  await page.waitForTimeout(1100);
  const prefs = (await call('get_preferences')).preferences;
  assert.equal(prefs.page_size, 24); const selectedIds = (await call('get_selection')).selection.words.map(word => word.id); assert.ok(selectedIds.length >= 13);
  await page.reload(); await ui.getByText('词库已连接', { exact: true }).waitFor();
  await expect(ui.getByRole('combobox', { name: '每页词数', exact: true })).toHaveValue('24');
  await expect(ui.locator('.library-selection-tools')).toContainText(`已选 ${selectedIds.length} 词`);
  const visibleNames = await ui.locator('.word-row strong').allTextContents();
  const expectedVisible = (await call('list_words')).words.filter(word => visibleNames.includes(word.word) && selectedIds.includes(word.id)).length;
  await expect(ui.locator('.word-row input[type=checkbox]:checked')).toHaveCount(expectedVisible);
  await ui.getByRole('searchbox').fill('retain');
  await expect(ui.locator('.word-row')).toHaveCount(1);
  await ui.getByRole('button', { name: '清除筛选', exact: true }).click();
  await expect(ui.locator('.word-row')).toHaveCount(24);

  // A held press colors the whole card; selection is immediate even offline.
  const firstCheck = ui.locator('.word-check input').first();
  const beforeChecked = await firstCheck.isChecked();
  const firstLabel = ui.locator('.word-check').first();
  assert.equal(await firstLabel.evaluate(node => getComputedStyle(node).webkitTapHighlightColor), 'rgba(0, 0, 0, 0)');
  const hit = await firstLabel.boundingBox();
  await page.mouse.move(hit.x + hit.width / 2, hit.y + hit.height / 2);
  await page.mouse.down();
  assert.equal(await ui.locator('.word-row').first().evaluate(node => node.matches(':has(.word-check:active)')), true);
  harness.setOffline(true);
  await page.mouse.up();
  await expect(firstCheck).toBeChecked({ checked: !beforeChecked });
  harness.setOffline(false);
  await firstCheck.setChecked(beforeChecked);

  for (const [width, height] of [[320, 740], [390, 844], [600, 854], [820, 1180], [1180, 820], [844, 390], [568, 320], [1280, 854]]) {
    await page.setViewportSize({ width, height });
    await expect.poll(()=>ui.locator('.app-shell').evaluate(node=>Math.round(node.getBoundingClientRect().height))).toBe(height-22);
    await ui.getByRole('button', { name: '词库', exact: true }).click();
    const dimensions = await ui.locator('html').evaluate(node => ({ width: node.clientWidth, scrollWidth: node.scrollWidth, height: node.clientHeight, scrollHeight: node.scrollHeight }));
    assert.ok(dimensions.scrollWidth <= dimensions.width + 1 && dimensions.scrollHeight <= dimensions.height + 1, `Outer overflow at ${width}×${height}`);
    if (width === 390 || width === 820) await page.screenshot({ animations: 'disabled', path: `${output}/library-${width}.png` });
    if (!await ui.locator('.filter-details summary').isVisible()) await ui.getByRole('button', { name: '展开筛选', exact: true }).click();
    await ui.locator('.filter-details summary').click();
    const filter = await ui.locator('.level-options').boundingBox();
    assert.ok(filter.x >= 0 && filter.x + filter.width <= width + 1 && filter.y >= 22 && filter.y + filter.height <= height + 1);
    await ui.locator('.level-options input').first().press('Escape');
    await expect(ui.locator('.level-options')).toHaveCount(0);
    await ui.getByRole('button', { name: '英语交流', exact: true }).click();
    await ui.getByRole('button', { name: '开始交流', exact: true }).scrollIntoViewIfNeeded();
    await expect(ui.getByRole('button', { name: '开始交流', exact: true })).toBeInViewport();
    if (width === 390) await page.screenshot({ animations: 'disabled', path: `${output}/conversation-portrait.png` });
    if (width === 1180) await page.screenshot({ animations: 'disabled', path: `${output}/conversation-landscape.png` });
    await ui.getByRole('button', { name: '历史文章', exact: true }).click();
    await ui.getByRole('searchbox', { name: '搜索历史文章', exact: true }).fill('not found');
    await expect(ui.getByRole('heading', { name: '没有找到这篇文章' })).toBeVisible();
    await ui.getByRole('button', { name: '清除搜索', exact: true }).click();
    await ui.getByRole('button', { name: new RegExp(article.title) }).click();
    const prose = ui.locator('.prose');
    assert.equal(await prose.evaluate(node => getComputedStyle(node).fontSize), '20px');
    await ui.locator('.word').filter({ hasText: /^retain$/i }).first().click();
    const reader = await ui.locator('.article-pane').boundingBox(), dictionary = await ui.locator('.definition-panel').boundingBox();
    if (width >= 540 && width > height) assert.ok(dictionary.x >= reader.x + reader.width, 'Landscape reading should keep side-by-side panes');
    if (width <= 600 && width < height) assert.ok(dictionary.y >= reader.y + reader.height, 'Portrait reading should keep a dictionary below the article');
    if (width === 390) await page.screenshot({ animations: 'disabled', path: `${output}/reading-portrait.png` });
    if (width === 844) await page.screenshot({ animations: 'disabled', path: `${output}/reading-short-landscape.png` });
    await ui.getByRole('button', { name: '关闭释义并返回所选词', exact: true }).click();
    await settingsButton.click();
    await dialog.getByRole('button', { name: '保存设置', exact: true }).scrollIntoViewIfNeeded();
    const modal = await dialog.boundingBox();
    assert.ok(modal.x >= 0 && modal.x + modal.width <= width + 1 && modal.y >= 22 && modal.y + modal.height <= height + 1);
    if (width === 390) await page.screenshot({ animations: 'disabled', path: `${output}/settings-portrait.png` });
    await dialog.getByRole('button', { name: '关闭设置', exact: true }).click();
  }
  await page.setViewportSize({ width: 1180, height: 820 });
  await ui.getByRole('button', { name: '词库', exact: true }).click();
  await page.screenshot({ animations: 'disabled', path: `${output}/library-landscape.png` });
  assert.deepEqual(errors, []);
  console.log('Polish verified: settings preview/cancel/save/retry/reload, host theme override, focus trap, bulk selection persistence, filter recovery, history search, 8 portrait/landscape sizes and reachable primary actions.');
} finally { await browser.close(); await harness.close(); service.close(); await rm(directory, { recursive: true, force: true }); }
